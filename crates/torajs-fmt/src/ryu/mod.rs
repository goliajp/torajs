    /// Reformat a `Decimal64` into the same string `f64::to_string`
    /// would emit (modulo the JS spec post-process), for direct
    /// comparison.
    ///
    /// This is a test helper — production formatting lives in
    /// `dtoa::format_f64_into` (P12.1-S3).
    fn dec_to_string(d: Decimal64) -> String {
        if d.mantissa == 0 {
            return if d.sign {
                String::from("-0")
            } else {
                String::from("0")
            };
        }
        let digits = format!("{}", d.mantissa);
        let n_digits = digits.len() as i32;
        let abs_exponent = d.exponent + n_digits - 1;
        let mut out = String::new();
        if d.sign {
            out.push('-');
        }
        // Match Rust's `f64::to_string` convention: use plain
        // decimal for "reasonable" magnitudes; use exponent form
        // otherwise. Reasonable here = same range as JS spec
        // shortest-roundtrip (-6 ≤ E < n_digits + d.exponent), but
        // for the unit-test convenience we mimic Rust's `{}`
        // (slightly different threshold).
        if abs_exponent >= -4 && abs_exponent < 16 {
            // Plain decimal form.
            if d.exponent >= 0 {
                out.push_str(&digits);
                for _ in 0..d.exponent {
                    out.push('0');
                }
            } else {
                let dot_pos = n_digits + d.exponent;
                if dot_pos <= 0 {
                    out.push_str("0.");
                    for _ in 0..(-dot_pos) {
                        out.push('0');
                    }
                    out.push_str(&digits);
                } else {
                    out.push_str(&digits[..dot_pos as usize]);
                    out.push('.');
                    out.push_str(&digits[dot_pos as usize..]);
                }
            }
        } else {
            // Exponential form: d.dddE±NN.
            out.push(digits.as_bytes()[0] as char);
            if n_digits > 1 {
                out.push('.');
                out.push_str(&digits[1..]);
            }
            out.push('e');
            let exp = abs_exponent;
            if exp >= 0 {
                out.push('+');
            }
            out.push_str(&format!("{}", exp));
        }
        out
    }

    /// Round-trip sanity: every sample's d2d output should parse
    /// back to the same f64 bits.
    fn assert_round_trip(d: f64) {
        let dec = d2d(d.to_bits());
        // Reconstruct as a string and parse with str::parse.
        let s = dec_to_string(dec);
        let parsed: f64 = s
            .parse()
            .unwrap_or_else(|_| panic!("could not parse Ryū output {s:?} back to f64 (input {d})"));
        assert_eq!(
            parsed.to_bits(),
            d.to_bits(),
            "round-trip failed: input {d} → {s:?} → parsed {parsed}"
        );
    }

