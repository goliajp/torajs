//! Ryū algorithm — IEEE 754 double → shortest-roundtrip decimal.
//!
//! Adams 2018 (PLDI):
//! <https://dl.acm.org/doi/10.1145/3192366.3192369>
//!
//! Entry point: [`d2d`] takes raw `f64::to_bits()` and returns
//! [`Decimal64`] = (sign, mantissa, exponent) such that
//! `mantissa · 10^exponent == d` (where d is the original f64
//! interpretation of the bits) for the SHORTEST decimal
//! representation that round-trips through
//! `str::parse::<f64>` back to the same bits.
//!
//! Special values (NaN, ±Infinity, ±0) are NOT handled here —
//! the [`crate::dtoa`] wrapper fast-paths those to literal
//! strings before invoking `d2d`. Subnormals ARE handled — they
//! take the normal Ryū code path with `e2 = 1 - bias - 52 - 2`
//! and `m2 = mantissa` (no implicit leading 1).
//!
//! Tables `POW5_INV_SPLIT[292]` and `POW5_SPLIT[326]` are
//! pre-generated by `scripts/gen_ryu_tables.py`; see
//! [`crate::ryu_tables`] for the const definitions and the
//! generator for the derivation formulas.

use crate::ryu_tables::{
    DOUBLE_POW5_BITCOUNT, DOUBLE_POW5_INV_BITCOUNT, POW5_INV_SPLIT, POW5_SPLIT,
};

const DOUBLE_MANTISSA_BITS: u32 = 52;
const DOUBLE_EXPONENT_BITS: u32 = 11;
const DOUBLE_BIAS: i32 = 1023;

/// Decimal representation of an f64, in the form
/// `sign · mantissa · 10^exponent`.
///
/// - `sign = true` if the input bits had the sign bit set.
/// - `mantissa` is the SHORTEST 1-17 digit decimal that
///   round-trips through `str::parse::<f64>`.
/// - `exponent` is the power-of-10 adjustment.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Decimal64 {
    pub mantissa: u64,
    pub exponent: i32,
    pub sign: bool,
}

/// Convert raw IEEE 754 double bits to a shortest-roundtrip
/// decimal representation.
///
/// Caller MUST ensure `bits` is not a NaN, ±Infinity, or ±0
/// encoding — those are fast-pathed at the wrapper layer.
pub fn d2d(bits: u64) -> Decimal64 {
    // ----------------------------------------------------------
    // Step 1: decode IEEE 754 fields.
    // ----------------------------------------------------------
    let sign = (bits >> (DOUBLE_MANTISSA_BITS + DOUBLE_EXPONENT_BITS)) != 0;
    let ieee_mantissa = bits & ((1u64 << DOUBLE_MANTISSA_BITS) - 1);
    let ieee_exponent =
        ((bits >> DOUBLE_MANTISSA_BITS) as u32) & ((1u32 << DOUBLE_EXPONENT_BITS) - 1);

    // ----------------------------------------------------------
    // Step 2: compute m2 * 2^e2 representation.
    //
    // We shift up by 2 bits to encode the round-up/round-down
    // halfway points as ±1 / ±2 offsets in 4·m2 units (per
    // Adams §3.1).
    // ----------------------------------------------------------
    let (e2, m2): (i32, u64) = if ieee_exponent == 0 {
        // Subnormal: no implicit leading 1.
        (
            1 - DOUBLE_BIAS - DOUBLE_MANTISSA_BITS as i32 - 2,
            ieee_mantissa,
        )
    } else {
        // Normal: implicit leading 1.
        (
            ieee_exponent as i32 - DOUBLE_BIAS - DOUBLE_MANTISSA_BITS as i32 - 2,
            (1u64 << DOUBLE_MANTISSA_BITS) | ieee_mantissa,
        )
    };

    let even = (m2 & 1) == 0;
    let accept_bounds = even;

    // ----------------------------------------------------------
    // Step 3: halfway bounds (scaled by 4).
    //
    //   mv = 4·m2          ← center
    //   mp = 4·m2 + 2      ← upper halfway
    //   mm = 4·m2 - 1 or 2 ← lower halfway (1 at binade boundary, 2 otherwise)
    // ----------------------------------------------------------
    let mv: u64 = 4 * m2;
    let mm_shift: u32 = (ieee_mantissa != 0 || ieee_exponent <= 1) as u32;

    // ----------------------------------------------------------
    // Step 4: scale by 10^(-e10) to bring (mm, mv, mp) · 2^e2
    //         into an integer range we can compare digit-by-digit.
    // ----------------------------------------------------------
    let (mut vr, mut vp, mut vm, e10);
    let mut vm_is_trailing_zeros = false;
    let mut vr_is_trailing_zeros = false;

    if e2 >= 0 {
        let q: u32 = log10_pow2(e2 as u32).saturating_sub((e2 > 3) as u32);
        e10 = q as i32;
        let k: i32 = DOUBLE_POW5_INV_BITCOUNT + pow5_bits(q as i32) - 1;
        let i: i32 = -e2 + q as i32 + k;
        vr = mul_pow5_inv_div_pow2(mv, q, i);
        vp = mul_pow5_inv_div_pow2(mv + 2, q, i);
        vm = mul_pow5_inv_div_pow2(mv - 1 - mm_shift as u64, q, i);

        if q <= 21 {
            // Tracking trailing zeros: vr/vp/vm divide cleanly by
            // 5 only if mv/mv+2/mm do.
            if mv % 5 == 0 {
                vr_is_trailing_zeros = multiple_of_power_of_5(mv, q);
            } else if accept_bounds {
                vm_is_trailing_zeros = multiple_of_power_of_5(mv - 1 - mm_shift as u64, q);
            } else {
                vp -= multiple_of_power_of_5(mv + 2, q) as u64;
            }
        }
    } else {
        let q: u32 = log10_pow5((-e2) as u32).saturating_sub(((-e2) > 1) as u32);
        e10 = q as i32 + e2;
        let i: i32 = -e2 - q as i32;
        let k: i32 = pow5_bits(i) - DOUBLE_POW5_BITCOUNT;
        let j: i32 = q as i32 - k;
        vr = mul_pow5_div_pow2(mv, i as u32, j);
        vp = mul_pow5_div_pow2(mv + 2, i as u32, j);
        vm = mul_pow5_div_pow2(mv - 1 - mm_shift as u64, i as u32, j);

        if q <= 1 {
            // {vr, vp, vm} are q digits short of representing mv
            // exactly; the missing trailing zeros come from the
            // 2^q factor of mv.
            vr_is_trailing_zeros = true;
            if accept_bounds {
                vm_is_trailing_zeros = mm_shift == 1;
            } else {
                vp -= 1;
            }
        } else if q < 63 {
            vr_is_trailing_zeros = multiple_of_power_of_2(mv, q);
        }
    }

    // ----------------------------------------------------------
    // Step 5: find shortest representation by removing trailing
    //         digits while vp and vm still differ in the high
    //         positions.
    // ----------------------------------------------------------
    let mut last_removed_digit: u8 = 0;
    let mut removed: u32 = 0;
    let output;

    if vm_is_trailing_zeros || vr_is_trailing_zeros {
        // Rare path (~0.01%): need to track trailing zeros for
        // correct rounding.
        loop {
            let vp_div10 = vp / 10;
            let vm_div10 = vm / 10;
            if vp_div10 <= vm_div10 {
                break;
            }
            let vm_mod10 = vm % 10;
            vm_is_trailing_zeros &= vm_mod10 == 0;
            vr_is_trailing_zeros &= last_removed_digit == 0;
            last_removed_digit = (vr % 10) as u8;
            vr /= 10;
            vp = vp_div10;
            vm = vm_div10;
            removed += 1;
        }
        if vm_is_trailing_zeros {
            while vm % 10 == 0 {
                vr_is_trailing_zeros &= last_removed_digit == 0;
                last_removed_digit = (vr % 10) as u8;
                vr /= 10;
                vm /= 10;
                removed += 1;
            }
        }
        if vr_is_trailing_zeros && last_removed_digit == 5 && vr % 2 == 0 {
            // Round-half-to-even adjustment.
            last_removed_digit = 4;
        }
        let round_up =
            (vr == vm && (!accept_bounds || !vm_is_trailing_zeros)) || last_removed_digit >= 5;
        output = vr + round_up as u64;
    } else {
        // Common path (~99.99%): no trailing-zero tracking
        // needed. Use a do-while-style loop so the final vp/vm
        // assignments are read for the next iteration's compare,
        // avoiding the `value never read` lint on the tail.
        loop {
            let vp_div10 = vp / 10;
            let vm_div10 = vm / 10;
            if vp_div10 <= vm_div10 {
                break;
            }
            last_removed_digit = (vr % 10) as u8;
            vr /= 10;
            vp = vp_div10;
            vm = vm_div10;
            removed += 1;
        }
        output = vr + ((vr == vm || last_removed_digit >= 5) as u64);
    }

    Decimal64 {
        mantissa: output,
        exponent: e10 + removed as i32,
        sign,
    }
}

/// Number of decimal digits in `v`, 1-17.
pub fn decimal_length(v: u64) -> u8 {
    debug_assert!(v < 10_000_000_000_000_000_000);
    if v >= 10_000_000_000_000_000 {
        17
    } else if v >= 1_000_000_000_000_000 {
        16
    } else if v >= 100_000_000_000_000 {
        15
    } else if v >= 10_000_000_000_000 {
        14
    } else if v >= 1_000_000_000_000 {
        13
    } else if v >= 100_000_000_000 {
        12
    } else if v >= 10_000_000_000 {
        11
    } else if v >= 1_000_000_000 {
        10
    } else if v >= 100_000_000 {
        9
    } else if v >= 10_000_000 {
        8
    } else if v >= 1_000_000 {
        7
    } else if v >= 100_000 {
        6
    } else if v >= 10_000 {
        5
    } else if v >= 1_000 {
        4
    } else if v >= 100 {
        3
    } else if v >= 10 {
        2
    } else {
        1
    }
}

