//! reads to resolve each runtime-helper FuncId. After Pass-0 batches
//! A-D (chunks 323-326) each declared its sub-system's FuncIds into a
//! holder struct (`InitA` / `InitB` / `InitC` / `InitD`), the
//! corresponding aggregate became a 467-LOC `Intrinsics { field:
//! init_X.group.subfield, ... }` literal inside `lower_inner`. This
//! sibling drains that literal out of the god-fn (chunk-330 of the
//! lower_inner RFC decomp, after Pass 0.5 / Pass 1 siblings in
//! chunks 328-329).
//!
//! Pure mechanical move: every field assignment is preserved
//! verbatim. The only non-init_X-derived field is
//! `env_drop_trivial`, which is built in `lower_inner` from a
//! freshly-synthesized FuncId and passed in as the first argument.

